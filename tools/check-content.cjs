'use strict';
const fs = require('fs');
const vm = require('vm');
const path = require('path');
const assert = require('assert/strict');
const crypto = require('crypto');
const acorn = require('./dependencies.cjs')('acorn');
const root = path.resolve(__dirname,'..');
const files = ['units.js','core.js','visuals.js','app.js'];
files.forEach(file => {
  const source = fs.readFileSync(path.join(root,'js',file),'utf8');
  acorn.parse(source,{ecmaVersion:2017,sourceType:'script'});
  assert.ok(!/\b(?:fetch|XMLHttpRequest|WebSocket|EventSource|sendBeacon|eval)\s*\(/.test(source),'network/eval forbidden: '+file);
  assert.ok(!/\b(?:alert|confirm|prompt)\s*\(/.test(source),'native blocking dialogs forbidden: '+file);
  assert.ok(!/\.innerHTML\s*\+=/.test(source),'incremental unsanitized DOM pattern: '+file);
});
let es2018Rejected = false;
try {acorn.parse('const a = {...b};',{ecmaVersion:2017});} catch (error) { es2018Rejected = true; }
assert.ok(es2018Rejected,'parser positive probe for newer syntax');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert.ok(!/<script[^>]*\btype\s*=\s*["']module/.test(html),'no module scripts');
assert.ok(!/(?:src|href)=["']https?:\/\//.test(html),'no remote scripts/styles/media');
const styles={};
fs.readdirSync(path.join(root,'css')).filter(x=>x.endsWith('.css')).forEach(file=>{styles[file]=fs.readFileSync(path.join(root,'css',file),'utf8');});
const imports=require('./check-imports.cjs');imports.probes();imports.validate(styles);
const window={localStorage:{getItem:()=>null,setItem:()=>{},removeItem:()=>{}}};
vm.runInNewContext(fs.readFileSync(path.join(root,'js/units.js'),'utf8'),{window});
vm.runInNewContext(fs.readFileSync(path.join(root,'js/core.js'),'utf8'),{window});
const {data,core}=window.BL;
assert.equal(data.grade,4);
assert.ok(data.units.length>=16,'grade4 coverage requires multiple domains/topics');
assert.equal(core.rejectedCount,0,'all material must pass review gate');
assert.equal(core.units().length,data.units.length,'no silently omitted units');
assert.deepEqual(Array.from(new Set(data.units.map(u=>u.domain))).sort(),['A','B','C','D']);
const original=JSON.parse(fs.readFileSync(path.join(root,'sources/grade4-math-codes.json'),'utf8'));
const codeRows=new Map(original.rows.map(r=>[r.code,r]));
assert.equal(crypto.createHash('sha256').update(fs.readFileSync(path.join(root,'sources/mext-20230901-codes.xlsx'))).digest('hex'),original.sha256,'original Excel checksum');
assert.equal(original.grade,4);
assert.equal(original.rows.length,138);
assert.equal(new Set(original.rows.map(r=>r.code)).size,138,'unique original codes');
assert.ok(codeRows.has('8250245A00000000'),'alphanumeric official code preserved');
const catalog={minecraft:['mc-build','mc-game','mc-redstone','mc-mod','mc-model'],programming:['prog-scratch','prog-js','prog-python','prog-unity','prog-roblox'],craft:['craft-cardboard','craft-accessory','craft-3dpen','craft-lego'],digital:['dig-3dprint','dig-stormworks'],media:['media-poster','media-movie','media-tokusatsu','media-stopmotion'],drawing:['draw-ipad','draw-stamp','draw-manga']};
assert.deepEqual(Array.from(data.categories.map(c=>c.id)).sort(),Object.keys(catalog).sort());
let questions=0,claims=0,games=0,prompts=0;
const types=new Set(), coverage=new Set();
data.units.forEach(unit=>{
  assert.ok(codeRows.has(unit.code),'official primary key '+unit.code);
  unit.coverageCodes.forEach(code=>{assert.ok(codeRows.has(code),'official linked code '+code);coverage.add(code);});
  assert.ok(new Set(unit.entries.map(e=>e.category)).size>=2,'two distinct interest paths '+unit.code);
  unit.entries.forEach(entry=>entry.activityIds.forEach(id=>assert.ok(catalog[entry.category].includes(id),'canonical activity id '+id)));
  assert.notEqual(unit.explanations.es.short,unit.explanations.es.detail,'real short/detail distinction');
  assert.notEqual(unit.explanations.es.short,unit.explanations.js.short,'real mode distinction');
  assert.notEqual(unit.explanations.es.detail,unit.explanations.js.detail,'real detailed mode distinction');
  assert.ok(unit.workedExample && unit.workedExample.steps.length >= 3,'step-by-step worked example '+unit.code);
  assert.ok(unit.misconception && unit.misconception.correction,'specific misconception guidance '+unit.code);
  unit.questions.forEach(q=>{questions++;types.add(q.type);assert.ok(core.grade(q,q.answer),'declared answer supported '+unit.code+'/'+q.id);});
  claims+=unit.claims.length;games++;prompts+=unit.buddy.length;
  assert.ok(core.grade(unit.game,unit.game.answer),'game answer supported');
  assert.equal(unit.review.humanApproval,null,'do not manufacture operator approval');
});
assert.ok(types.has('number') && types.has('choice') && types.has('order'),'all three response types');
// Every leaf in instructional content is mapped, including thinking and applying.
const leaves=original.rows.filter(r=>r.code.startsWith('8250243') && !original.rows.some(other=>other.code!==r.code && other.code.startsWith(r.code.replace(/0+$/,'')) && other.code.replace(/0+$/,'').length>r.code.replace(/0+$/,'').length));
leaves.forEach(row=>assert.ok(coverage.has(row.code),'unmapped curriculum leaf '+row.code));
const result={units:data.units.length,questions,games,buddyPrompts:prompts,claims,officialRows:original.rows.length,mappedCodes:coverage.size,contentLeaves:leaves.length,sourceSha256:original.sha256,unitsSha256:crypto.createHash('sha256').update(fs.readFileSync(path.join(root,'js/units.js'))).digest('hex')};
fs.mkdirSync(path.join(root,'output'),{recursive:true});
fs.writeFileSync(path.join(root,'output/content-check.json'),JSON.stringify(result,null,2)+'\n');
console.log('ES2017=PASS CONTENT_CHECK='+JSON.stringify(result));
